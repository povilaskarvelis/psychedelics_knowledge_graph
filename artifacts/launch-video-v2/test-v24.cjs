const fs=require('fs'),assert=require('node:assert/strict');
const {Easing,interpolate}=require('remotion');
require('./test-v23.cjs');
const read=file=>fs.readFileSync(__dirname+'/src/product-v24/'+file,'utf8');
const growth=read('Growth.jsx'),film=read('ProductFilm.jsx');
assert(growth.includes('M 1070 755 C 1330 738 1580 585 1745 250'));
assert(250<850-2100*510/2000,'Arrow ends above the tallest bar');
assert(1745>1635,'Arrow extends farther right than V23');
const expression=growth.split('strokeDashoffset={1-')[1].split('} opacity=')[0];
const progress=new Function('f','interpolate','Easing','return '+expression);
assert(progress(118,interpolate,Easing)<.9,'Arrow must visibly continue after bars complete');
assert.equal(progress(140,interpolate,Easing),1);
assert(growth.includes('p(f,140,146)'));
assert(read('Living.jsx').includes('Always stay up to date'));
assert(!read('Living.jsx').includes('Updated as new papers arrive'));
assert(film.includes("from './Living'"));
assert(!film.includes('Audio'));
assert.equal([...film.matchAll(/durationInFrames=\{(\d+)\}/g)].reduce((n,m)=>n+Number(m[1]),0)-48,2794);
console.log('PASS: arrow extends above tallest bar, finishes after bars, and new closing copy; silent duration unchanged.');
